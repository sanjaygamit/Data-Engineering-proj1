CREATE OR REPLACE VIEW ANALYTICS.FARMER_SUMMARY AS
SELECT
  f.FARMER_ID,
  f.FULL_NAME,
  f.STATE,
  COUNT(DISTINCT fa.FARM_ID) AS FARMS,
  COUNT(DISTINCT cp.PLAN_ID) AS ACTIVE_CROPS,
  MAX(cp.HARVEST_DATE)       AS NEXT_HARVEST,
  COUNT(DISTINCT pi.INCIDENT_ID) AS PEST_EVENTS_30D
FROM CORE.FARMER f
LEFT JOIN CORE.FARM fa             ON fa.FARMER_ID = f.FARMER_ID
LEFT JOIN AGRONOMY.CROP_PLAN cp    ON cp.FARM_ID = fa.FARM_ID AND cp.STATUS='ACTIVE'
LEFT JOIN AGRONOMY.PEST_INCIDENT pi ON pi.FARM_ID = fa.FARM_ID AND pi.EVENT_TS >= DATEADD('day', -30, CURRENT_TIMESTAMP())
GROUP BY 1,2,3;

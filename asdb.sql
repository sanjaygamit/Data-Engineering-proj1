-- Upsert from staging to core
CREATE OR REPLACE PROCEDURE STAGING.MERGE_FARMERS()
RETURNS STRING
LANGUAGE SQL
AS
$$
INSERT INTO CORE.FARMER (
  FARMER_ID, FULL_NAME, PHONE, LANG, ADDRESS_LINE1, VILLAGE, DISTRICT, STATE, PINCODE, LAT, LON, LANDHOLDING_HA, CREATED_AT
)
SELECT
  COALESCE(HASH(FULL_NAME||PHONE||NVL(PINCODE,''))::STRING, UUID_STRING()),
  FULL_NAME, PHONE, LANG, ADDRESS_LINE1, VILLAGE, DISTRICT, STATE, PINCODE, LAT, LON, LANDHOLDING_HA, CURRENT_TIMESTAMP()
FROM STAGING.FARMER_CSV_LANDING;
$$;

-- Optional: Streams & Tasks for incremental pipelines
CREATE OR REPLACE STREAM STAGING.FARMER_CSV_LANDING_STREAM ON TABLE STAGING.FARMER_CSV_LANDING APPEND_ONLY=TRUE;

CREATE OR REPLACE TASK STAGING.LOAD_FARMERS_TASK
  WAREHOUSE = AGRI_HELP_WH
  SCHEDULE = 'USING CRON 30 * * * * Asia/Kolkata'
AS
  CALL STAGING.MERGE_FARMERS();


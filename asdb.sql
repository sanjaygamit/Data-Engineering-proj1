-- 7) Governance: PII tag + basic masking policy
CREATE OR REPLACE TAG ANALYTICS.PII_TAG ALLOWED_VALUES ('PII','NON_PII');
CREATE OR REPLACE MASKING POLICY ANALYTICS.MASK_PHONE AS (val STRING) RETURNS STRING ->
  CASE
    WHEN CURRENT_ROLE() IN ('AGRI_HELP_ADMIN','AGRI_HELP_DEV') THEN val
    ELSE REGEXP_REPLACE(val, '(\\d{2})\\d{6}(\\d{2})', '\\1******\\2')
  END;

